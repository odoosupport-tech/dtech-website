// Builds assets/dovechat.css (and .min.css), a copy of the Dovesoft chat widget's
// stylesheet whose rules only reach the widget's own elements.
//
//   node tools/scope-chat-css.js           fetch the vendor file and rewrite assets/dovechat(.min).css
//   node tools/scope-chat-css.js --check   exit 1 if the vendor file changed since the last rewrite
//
// The widget's loader (ccut.in webTool-*.js) injects mainWebChatRed.css into every
// page. That file is a Tailwind build aimed at a page of its own: its theme tokens,
// preflight and font rules target :root, html, body, img, a, h1-h6 and more, many with
// !important inside cascade layers, which outranks every rule on the site (its
// `img { height:auto !important }` blew case-study logos up to their natural size).
// The pages load this scoped copy instead, and assets/chat-widget.js removes the
// vendor link as soon as the loader adds it.
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const postcss = require('postcss');
const { transform } = require('lightningcss');

const SOURCE = 'https://ccut.in/upload/surveyCommon/mainWebChatRed.css';
const OUT = path.resolve(__dirname, '../assets/dovechat.css');
const OUT_MIN = path.resolve(__dirname, '../assets/dovechat.min.css');
// The elements mainWebChatSocketRed.js appends to <body>; all of the widget's markup
// is built inside them.
const ROOTS = ':where(.dovechat4474, #dove_4474_notification, #doveloader)';
const ALREADY_SCOPED = /^(?:\.dovechat4474|#dove_4474_notification|#doveloader)(?![\w-])/;
// Selectors for the document itself: the widget roots stand in for them, so the
// tokens and fonts they set still reach the widget by inheritance.
const DOCUMENT = new Set([':root', ':host', 'html', 'body']);
const HASH_LINE = /^\/\* Source sha256: ([0-9a-f]{64}) \*\/$/m;

// Index where the first compound selector of `selector` ends (first combinator outside
// brackets), and where a :where() can go inside it (before any pseudo-element).
function firstCompound(selector) {
  let depth = 0;
  let pseudoElement = -1;
  for (let i = 0; i < selector.length; i++) {
    const ch = selector[i];
    if (ch === '(' || ch === '[') depth++;
    else if (ch === ')' || ch === ']') depth--;
    else if (depth === 0) {
      if (/[\s>+~]/.test(ch)) return { end: i, insertAt: pseudoElement < 0 ? i : pseudoElement };
      if (ch === ':' && selector[i + 1] === ':' && pseudoElement < 0) pseudoElement = i;
    }
  }
  return { end: selector.length, insertAt: pseudoElement < 0 ? selector.length : pseudoElement };
}

// The same elements @scope (roots) would give: the roots' descendants, and the roots
// themselves when the selector's first compound matches them. :where() adds no
// specificity, so the vendor rules keep their order among themselves.
function scopeSelector(raw) {
  const selector = raw.trim();
  if (DOCUMENT.has(selector)) return [ROOTS];
  if (ALREADY_SCOPED.test(selector)) return [selector];
  const { insertAt } = firstCompound(selector);
  const onRoot = selector.startsWith('*')
    ? ROOTS + selector.slice(1)
    : selector.slice(0, insertAt) + ROOTS + selector.slice(insertAt);
  return [`${ROOTS} ${selector}`, onRoot];
}

function isTopLevelStyleRule(rule) {
  for (let node = rule.parent; node && node.type !== 'root'; node = node.parent) {
    if (node.type === 'rule') return false; // nested rules inherit the parent's scope
    if (node.type === 'atrule' && /keyframes$/i.test(node.name)) return false;
  }
  return true;
}

function scope(css) {
  const root = postcss.parse(css);
  // Google Fonts is outside the CSP's style-src, so the browser already refuses this.
  root.walkAtRules('import', (rule) => rule.remove());
  root.walkRules((rule) => {
    if (!isTopLevelStyleRule(rule)) return;
    rule.selectors = [...new Set(rule.selectors.flatMap(scopeSelector))];
  });
  return root.toString();
}

async function fetchVendor() {
  const res = await fetch(SOURCE, { signal: AbortSignal.timeout(20000) });
  if (!res.ok) throw new Error(`GET ${SOURCE} answered HTTP ${res.status}`);
  const css = await res.text();
  if (!css.includes('.dovechat4474')) throw new Error(`${SOURCE} no longer mentions .dovechat4474; the widget markup may have changed`);
  return css;
}

async function main() {
  const css = await fetchVendor();
  const sha = crypto.createHash('sha256').update(css).digest('hex');

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? HASH_LINE.exec(fs.readFileSync(OUT, 'utf8')) : null;
    if (current && current[1] === sha) {
      console.log('assets/dovechat.css matches the vendor stylesheet');
      return;
    }
    console.error(`${SOURCE} changed; run node tools/scope-chat-css.js && npm run build`);
    process.exitCode = 1;
    return;
  }

  const header = [
    '/* Generated by tools/scope-chat-css.js. Do not edit; rerun the tool instead. */',
    `/* Source: ${SOURCE} */`,
    `/* Source sha256: ${sha} */`,
  ].join('\n');
  const scoped = `${header}\n${scope(css)}`;
  // Minified here rather than by build-css.js: clean-css drops nested (&) rules and
  // the @property that follows them, which the widget's Tailwind utilities rely on.
  const { code, warnings } = transform({ filename: 'dovechat.css', code: Buffer.from(scoped), minify: true, errorRecovery: true });
  for (const w of warnings) console.warn(`dovechat.css: ${w.message}`);
  fs.writeFileSync(OUT, scoped);
  fs.writeFileSync(OUT_MIN, code);
  console.log(`wrote assets/dovechat.css and dovechat.min.css (source sha256 ${sha.slice(0, 12)})`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
